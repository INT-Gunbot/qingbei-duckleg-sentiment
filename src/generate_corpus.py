def weighted_pick(pairs):
    r, acc = random.random(), 0
    for k, w in pairs:
        acc += w
        if r <= acc:
            return k
    return pairs[-1][0]

def sample_hour(day):
    hw = HOUR_W[day]
    return weighted_pick([(h, w) for h, w in hw.items()])

def sample_stance(day, utype):
    pool = USER_STANCE.get(utype, list(STANCES.keys()))
    w = [(s, DAILY_STANCE[day].get(s, 0.01) * STANCE_USER_AFF.get(s, {}).get(utype, 1.0)) for s in pool]
    return weighted_pick(w)

def sample_engagement(utype, day):
    base = {"媒体蓝V(新华社/澎湃等)": (8000, 3000, 30000), "大V自媒体": (2500, 1200, 9000),
            "法律/时评博主": (1200, 600, 4000), "美食探店博主": (900, 500, 3000)}.get(utype, (30, 15, 120))
    rp_lo, lk_lo, lk_hi = base
    decay = 1.0 if day in ("2026-06-10", "2026-06-11") else 0.45
    rp = int(random.randint(rp_lo, max(rp_lo + 1, lk_hi // 6)) * decay)
    cm = int(random.randint(max(1, lk_lo // 10), max(2, lk_hi // 10)) * decay)
    lk = int(random.randint(lk_lo, lk_hi) * decay)
    return rp, cm, lk

def main():
    rows, rid = [], 0
    real_used = 0
    for day, (real_vol, sample_n) in DAILY.items():
        for _ in range(sample_n):
            h = sample_hour(day)
            ts = f"{day} {h:02d}:{random.randint(0,59):02d}"
            plat = weighted_pick(PLATFORMS)
            utype = weighted_pick(USER_TYPES)
            stance = sample_stance(day, utype)
            text, real = random.choice(STANCES[stance])
            real_used += 1 if real else 0
            rp, cm, lk = sample_engagement(utype, day)
